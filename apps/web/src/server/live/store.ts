/**
 * Snapshot storage.
 *
 * Read order:
 *   1. the bundled snapshot (committed, so a cold serverless function has real
 *      channels before its first successful network fetch);
 *   2. the filesystem snapshot at CLOUDPLAY_LIVE_STATE_DIR, written after every
 *      successful import. Vercel functions share /tmp across warm invocations,
 *      so this makes refreshes cheap; on a long-lived host it survives restarts.
 *
 * Writes are atomic (write temp file, then rename) so a crash mid-write can
 * never leave a truncated JSON document behind.
 */
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import type { LiveSnapshot } from './types';

const requireFromHere = createRequire(__filename);

/** Committed fallback; regenerated by `node scripts/live-snapshot.js`. */
export function bundledSnapshot(): LiveSnapshot | null {
  try {
    const loaded = requireFromHere('./snapshot/iq.json') as LiveSnapshot;
    return loaded && loaded.version === 1 && Array.isArray(loaded.channels) ? loaded : null;
  } catch {
    return null;
  }
}

function stateFile(): string | null {
  const dir = process.env.CLOUDPLAY_LIVE_STATE_DIR;
  if (!dir) {
    // Serverless: /tmp is writable and shared between warm invocations.
    if (process.env.VERCEL) return join(tmpdir(), 'cloudplay-live', 'snapshot.json');
    return null;
  }
  if (!dir.startsWith('/') && !/^[A-Za-z]:[\\/]/.test(dir)) return null;
  return join(dir, 'snapshot.json');
}

export async function readStoredSnapshot(): Promise<LiveSnapshot | null> {
  const file = stateFile();
  if (!file) return null;
  try {
    const raw = await readFile(file, 'utf8');
    const parsed = JSON.parse(raw) as LiveSnapshot;
    if (!parsed || parsed.version !== 1 || !Array.isArray(parsed.channels)) return null;
    return parsed;
  } catch {
    return null;
  }
}

export async function writeStoredSnapshot(snapshot: LiveSnapshot): Promise<boolean> {
  const file = stateFile();
  if (!file) return false;
  try {
    await mkdir(dirname(file), { recursive: true });
    const temporary = `${file}.${process.pid}.${Date.now()}.tmp`;
    await writeFile(temporary, JSON.stringify(snapshot), 'utf8');
    await rename(temporary, file);
    return true;
  } catch {
    return false;
  }
}

/** Test seam: allows the acceptance tests to point storage at a temp directory. */
export function storageTarget(): string | null {
  return stateFile();
}
